def normalize_item_name(name: str) -> str:
    """标准化物品名称"""
    if not name:
        return ""
    
    name = name.strip()
    
    # 1. 查表映射
    if name in ITEM_MAPPINGS:
        return ITEM_MAPPINGS[name]
    
    # 2. 去除括号内的修饰词 (可选，视情况而定)
    # name = re.sub(r'\(.*?\)', '', name).strip()
    
    return name

def normalize_item_type(item_type: str) -> str:
    """标准化物品类型"""
    if not item_type:
        return "其他"
    
    item_type = item_type.strip()
    
    # 处理 "兵器/飞剑" 这种组合类型，取第一个或查表
    first_type = item_type.split('/')[0].strip()
    
    if first_type in TYPE_MAPPINGS:
        return TYPE_MAPPINGS[first_type]
    
    if item_type in TYPE_MAPPINGS:
        return TYPE_MAPPINGS[item_type]
        
    return item_type

