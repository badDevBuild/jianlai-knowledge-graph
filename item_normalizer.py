def normalize_item_grade(grade_str: str) -> str:
    """
    标准化物品品级

    将碎片化的 grade 值归并为前端 ItemGrade 枚举定义的 7 种:
    凡物、灵器、法宝、半仙兵、仙兵、神器、未知

    Args:
        grade_str: 原始品级字符串

    Returns:
        标准化后的品级 (凡物/灵器/法宝/半仙兵/仙兵/神器/未知)
    """
    if not grade_str:
        return "未知"

    grade_str = grade_str.strip()

    # 1. 查表映射
    if grade_str in GRADE_MAPPINGS:
        return GRADE_MAPPINGS[grade_str]

    # 2. 已经是标准品级的直接返回
    standard_grades = {"凡物", "灵器", "法宝", "半仙兵", "仙兵", "神器", "未知"}
    if grade_str in standard_grades:
        return grade_str

    # 3. 未知品级
    return "未知"


def is_valid_item(name: str) -> bool:
    """判断是否为有效物品"""
    if not name:
        return False
    
    if name in IGNORED_ITEMS:
        return False
    
    # 过滤过短的纯通用词 (需谨慎)
    if len(name) == 1 and name in ["剑", "刀", "钱"]:
        return False
        
    return True
