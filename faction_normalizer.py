def normalize_faction_type(type_str: str) -> str:
    """
    标准化势力类型

    将碎片化的 type 值归并为约 15 种标准类型:
    宗门、家族、王朝、书院、教派、官方机构、军事组织、
    江湖门派、妖族势力、神道势力、商业组织、地方势力、
    跨界组织、其他

    Args:
        type_str: 原始势力类型

    Returns:
        标准化后的势力类型
    """
    if not type_str:
        return "其他"

    type_str = type_str.strip()

    # 1. 查表映射
    if type_str in FACTION_TYPE_MAPPINGS:
        return FACTION_TYPE_MAPPINGS[type_str]

    # 2. 已经是标准类型的直接返回
    standard_types = {
        "宗门", "家族", "王朝", "书院", "教派", "官方机构",
        "军事组织", "江湖门派", "妖族势力", "神道势力",
        "商业组织", "地方势力", "跨界组织", "其他"
    }
    if type_str in standard_types:
        return type_str

    # 3. 未知类型归为"其他"
    return "其他"

