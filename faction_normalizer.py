# 4. 辅助函数：合并势力描述
# ============================================================

def merge_faction_descriptions(desc1: str, desc2: str) -> str:
    """
    合并两个势力描述（当同义词合并时使用）
    
    Args:
        desc1: 第一个描述
        desc2: 第二个描述
        
    Returns:
        合并后的描述
    """
    if not desc1:
        return desc2
    if not desc2:
        return desc1
    if desc1 == desc2:
        return desc1
    
    # 简单拼接，用分号分隔
    return f"{desc1}；{desc2}"


