def normalize_faction(name: str) -> str:
    """
    标准化势力名称

    处理逻辑：
    0. 去掉括号注释 "落魄山(预备)" → "落魄山"
    1. 应用同义词映射 (FACTION_MAPPINGS)
    2. 应用白名单合并映射 (faction_whitelist.json)

    Args:
        name: 原始势力名称

    Returns:
        标准化后的势力名称，无效返回空字符串
    """
    if not name:
        return ""

    name = name.strip()

    # 0. 去掉括号注释: "落魄山(预备)" → "落魄山", "大骊 (地支)" → "大骊"
    name = re.sub(r'\s*[（(][^）)]*[）)]', '', name).strip()

    # 0.5. 去掉括号后变成无效值
    if not name or name == "无":
        return ""

    # 1. 应用原有同义词映射（不 early return，继续检查白名单）
    if name in FACTION_MAPPINGS:
        name = FACTION_MAPPINGS[name]

    # 2. 应用白名单合并映射（可叠加：FACTION_MAPPINGS 的结果可能还需要白名单映射）
    if name in _WHITELIST_MERGES:
        name = _WHITELIST_MERGES[name]

    return name


def normalize_faction_multi(raw_name: str) -> list:
    """
    将一个原始标签拆分并标准化为多个势力名。

    处理 "/" 分隔的多势力标签，如 "落魄山/青萍剑宗" → ["落魄山", "青萍剑宗"]

    Args:
        raw_name: 原始势力标签

    Returns:
        标准化后的势力名列表（去重，过滤无效）
    """
    if not raw_name:
        return []

    # 拆分 / 和 ／（支持全角半角，允许前后空格）
    parts = re.split(r'\s*/\s*|／', raw_name)

    results = []
    for part in parts:
        norm = normalize_faction(part)
        if norm and is_valid_faction(norm):
            results.append(norm)

    return list(dict.fromkeys(results))  # 去重保序


def is_valid_faction(name: str) -> bool:
    """
    检查势力名称是否有效

    Args:
        name: 势力名称（应已标准化）

    Returns:
        True if valid, False if should be ignored
    """
    if not name:
        return False
    if name in IGNORED_FACTIONS:
        return False
    if name in _WHITELIST_LOCATIONS:
        return False
    return True


