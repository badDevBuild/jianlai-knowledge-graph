def normalize_location_name(name):
    if not name:
        return ""
    name = name.strip()
    return LOCATION_MAPPINGS.get(name, name)

def normalize_location_type(loc_type):
    if not loc_type:
        return "地点"
    loc_type = loc_type.strip()
    return TYPE_MAPPINGS.get(loc_type, loc_type)

def is_valid_location(name):
    if not name:
        return False
    if name in IGNORED_LOCATIONS:
        return False
    if len(name) < 2: # 单字地点通常无效，除“山”、“河”等特定外，但通常会有前后缀
        return False
    return True
