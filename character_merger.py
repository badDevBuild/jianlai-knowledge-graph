def get_canonical_name(name: str) -> str:
    """获取人物的标准名称（如果是别名则返回主人物名）"""
    return CHARACTER_ALIASES.get(name, name)


def merge_character_data(main_char: dict, alias_char: dict) -> dict:
    """
    将别名人物的数据合并到主人物
    
    合并策略：
    - aliases: 合并去重
    - bio_list: 合并去重
    - cultivation_log: 合并
    - factions: 合并去重
    - tags: 合并去重
    - quotes: 合并
    - relations: 合并（同一目标的关系合并 type 和 evidence）
    """
    # 添加别名本身
    if isinstance(main_char.get("aliases"), set):
        main_char["aliases"].add(alias_char["name"])
    elif isinstance(main_char.get("aliases"), list):
        if alias_char["name"] not in main_char["aliases"]:
            main_char["aliases"].append(alias_char["name"])
    
    # 合并 aliases
    alias_aliases = alias_char.get("aliases", set() if isinstance(main_char.get("aliases"), set) else [])
    if isinstance(main_char.get("aliases"), set):
        main_char["aliases"].update(alias_aliases)
    else:
        for a in alias_aliases:
            if a not in main_char["aliases"]:
                main_char["aliases"].append(a)
    
    # 合并 bio_list
    if "bio_list" in alias_char:
        if "bio_list" not in main_char:
            main_char["bio_list"] = []
        for bio in alias_char.get("bio_list", []):
            if bio not in main_char["bio_list"]:
                main_char["bio_list"].append(bio)
    
    # 合并 bio_summary（如果主人物没有的话）
    if not main_char.get("bio_summary") and alias_char.get("bio_summary"):
        main_char["bio_summary"] = alias_char["bio_summary"]
    
    # 合并 cultivation_log
    main_char["cultivation_log"].extend(alias_char.get("cultivation_log", []))
    
    # 合并 factions
    if isinstance(main_char.get("factions"), set):
        main_char["factions"].update(alias_char.get("factions", set()))
    else:
        for f in alias_char.get("factions", []):
            if f not in main_char["factions"]:
                main_char["factions"].append(f)
    
    # 合并 tags
    if isinstance(main_char.get("tags"), set):
        main_char["tags"].update(alias_char.get("tags", set()))
    else:
        for t in alias_char.get("tags", []):
            if t not in main_char["tags"]:
                main_char["tags"].append(t)
    
    # 合并 quotes
    main_char["quotes"].extend(alias_char.get("quotes", []))
    
    # 合并 relations
    for target, rel_data in alias_char.get("relations", {}).items():
        # 如果目标也是别名，转换为标准名
        canonical_target = get_canonical_name(target)
        
        if canonical_target not in main_char["relations"]:
            main_char["relations"][canonical_target] = rel_data
        else:
            # 合并同一目标的关系
            existing = main_char["relations"][canonical_target]
            if isinstance(existing["type"], set):
                existing["type"].update(rel_data.get("type", set()))
            else:
                for t in rel_data.get("type", []):
                    if t not in existing["type"]:
                        existing["type"].append(t)
            existing["strength"] = max(existing["strength"], rel_data.get("strength", 0))
            existing["evidence"].extend(rel_data.get("evidence", []))
    
    return main_char
